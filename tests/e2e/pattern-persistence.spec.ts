import { test, expect } from "@playwright/test";
import { decodeExploration } from "../../lib/client/exploration-url";
import { savedViewLabels } from "../../lib/i18n/saved-views";
import { workspaceLabels } from "../../lib/i18n/workspace";
import { entryLabels } from "../../lib/i18n/exploration-entry";
import { relationText } from "../../lib/i18n/relation-condition";
import { overviewLabels } from "../../lib/i18n/entity-overview";
const root = "2b7c6289-d050-4dc0-93e3-9307681253cc";
for (const [locale, width] of [["ja", 1280], ["en", 390]] as const) test(`pattern persistence ${locale} ${width}`, async ({ browser }, info) => {
  const ctx = await browser.newContext({ viewport: { width, height: 900 }, isMobile: width < 800, hasTouch: width < 800 });
  await ctx.addInitScript(() => localStorage.setItem("plunode:privacy:v1", '{"analytics":false,"ads":false}'));
  const page = await ctx.newPage(), errors: string[] = [], reads: number[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("response", async r => { if (r.url().endsWith("/api/discovery/paths") && r.request().method() === "POST") reads.push(await r.finished().then(() => r.request().timing().responseEnd)); });
  const entry = entryLabels(locale), text = relationText(locale), views = savedViewLabels(locale), workspace = workspaceLabels(locale);
  const graph = page.locator("#explorer-graph"), state = () => { const url = new URL(page.url()); return decodeExploration(url.searchParams.get("s")!, root, "public-kg"); };
  const nav = page.locator('nav[aria-label="'+(locale === "en" ? "Explorer panels" : "探索画面の切り替え")+'"]');
  const openTool = async (label: string) => { if (width < 800) await nav.getByRole("button", { name: locale === "en" ? "Search" : "検索", exact: true }).click(); await page.locator("#explorer-search").getByRole("button", { name: label, exact: true }).click(); };
  const returnGraph = async () => { if (width < 800) await nav.getByRole("button", { name: "Graph", exact: true }).click(); };
  await page.goto(info.project.use.baseURL! + (locale === "en" ? "/en" : "") + `/explore/${root}`);
  await expect(page.getByTestId("exploration-root")).toContainText("PLUTO");
  await expect.poll(() => new URL(page.url()).searchParams.get("s")).toBeTruthy();
  await graph.getByRole("button", { name: entry.edit, exact: true }).click();
  let dialog = page.getByRole("dialog"); await dialog.getByRole("radio", { name: text.pattern, exact: true }).check();
  await dialog.getByRole("button", { name: entry.cancel, exact: true }).click();
  expect(state().relation.type).toBe("adjacent");
  await graph.getByRole("button", { name: entry.edit, exact: true }).click();
  dialog = page.getByRole("dialog"); await dialog.getByRole("radio", { name: text.pattern, exact: true }).check();
  await page.screenshot({ path: info.outputPath("editor.png"), animations: "disabled" });
  await dialog.getByRole("button", { name: entry.apply, exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  const paths = page.getByRole("region", { name: text.routes, exact: true });
  await expect(paths.locator("li")).toHaveCount(10);
  const layout = await page.getByTestId("graph-canvas").evaluate(el => {
    const cy = (el as unknown as { _cyreg: { cy: import("cytoscape").Core } })._cyreg.cy;
    return { nodes: cy.nodes().length, positions: new Set(cy.nodes().map(n => JSON.stringify(n.position()))).size };
  });
  expect(layout.positions).toBe(layout.nodes); expect(layout.nodes).toBe(3);
  await page.screenshot({ path: info.outputPath("applied.png"), animations: "disabled" });
  await expect.poll(() => state().relation.type).toBe("pattern");
  await graph.getByRole("button", { name: text.openNext, exact: true }).click();
  await expect(paths.getByRole("button", { name: text.close, exact: true })).toHaveCount(2);
  await expect.poll(() => { const ex = state().execution; return ex.type === "pattern" && ex.routes.filter(r => r.open).length; }).toBe(2);
  await paths.getByRole("button", { name: text.close, exact: true }).first().click();
  await expect.poll(() => { const ex = state().execution; return ex.type === "pattern" && ex.routes.slice(0, 2).map(r => r.open); }).toEqual([false, true]);
  const closed = state().execution;
  await paths.getByRole("button", { name: new RegExp(text.evidence) }).filter({ visible: true }).nth(2).click();
  if (width < 800) await expect(page.locator("#explorer-detail")).toBeVisible();
  await expect(page.locator("#explorer-detail")).toContainText(locale === "en" ? "Source" : "出典");
  if (width < 800) await nav.getByRole("button", { name: "Graph", exact: true }).click();
  await openTool(workspace.launch);
  dialog = page.getByRole("dialog"); await dialog.getByLabel(workspace.name, { exact: true }).fill("pattern session");
  await dialog.getByRole("button", { name: workspace.save, exact: true }).click();
  await expect(dialog).toContainText(workspace.saved);
  await dialog.getByRole("button", { name: workspace.close, exact: true }).click();
  await openTool(views.launch);
  dialog = page.getByRole("dialog"); await dialog.getByLabel(views.name, { exact: true }).fill("pattern view");
  await dialog.getByRole("button", { name: views.save, exact: true }).click();
  await expect(dialog).toContainText(views.saved); await dialog.getByRole("button", { name: views.close, exact: true }).click(); await returnGraph();
  await page.reload(); await expect(paths.locator("li")).toHaveCount(10);
  await expect.poll(() => state().execution).toEqual(closed);
  await graph.getByRole("button", { name: text.free, exact: true }).click();
  await expect.poll(() => state().relation.type).toBe("adjacent");
  expect(state().relation).toMatchObject({ predicates: ["CONTRIBUTED_TO"], polarity: "affirmed", contributionRoles: null });
  await graph.getByRole("button", { name: overviewLabels(locale).restore, exact: true }).click();
  await expect(paths.locator("li")).toHaveCount(10); await expect.poll(() => state().execution).toEqual(closed);
  await graph.getByRole("button", { name: text.free, exact: true }).click(); await expect.poll(() => state().relation.type).toBe("adjacent");
  await openTool(workspace.launch); dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: workspace.open, exact: true }).click();
  await expect(paths.locator("li")).toHaveCount(10); await expect.poll(() => state().execution).toEqual(closed);
  await openTool(views.launch); dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: views.openNamed("pattern view"), exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0); await expect(paths.locator("li")).toHaveCount(10);
  await expect(paths.getByRole("button", { name: text.close, exact: true })).toHaveCount(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: info.outputPath("pattern.png"), fullPage: true, animations: "disabled" });
  console.log(JSON.stringify({ locale, pathResponseMilliseconds: reads }));
  await info.attach("path-timings", { body: JSON.stringify({ milliseconds: reads }), contentType: "application/json" });
  expect(errors).toEqual([]); await ctx.close();
});
