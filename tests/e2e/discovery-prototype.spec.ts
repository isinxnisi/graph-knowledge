test("institution connections, pivots, error/retry and rapid delayed changes", async ({ page }, info) => {
  await page.goto(info.project.use.baseURL! + "/discovery-lab");
  const dialog = page.getByRole("dialog"), results = page.getByTestId("prototype-results");
  await dialog.locator(`[data-seed="${princeton}"]`).getByRole("button").click();
  await expect(results.getByTestId("prototype-claim").first()).toBeVisible();
  await expect(dialog.getByText(/同時在籍・交流・共同研究の証明ではありません/)).toBeVisible();
  await results.getByRole("button", { name: /の先へ/ }).first().click();
  await expect(results).not.toHaveAttribute("data-updating", "true");
  await expect(results.getByTestId("prototype-claim").first()).toBeVisible();
  await dialog.getByRole("button", { name: "一つ戻す", exact: true }).click();
  await expect(results).not.toHaveAttribute("data-updating", "true");
  await page.route("**/neighbors?**", async route => {
    const predicates = new URL(route.request().url()).searchParams.get("predicates");
    if (predicates === "INFLUENCED_BY") return route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { message: "Test outage" } }) });
    if (predicates === "CONTRIBUTED_TO") await new Promise(resolve => setTimeout(resolve, 600));
    await route.continue();
  });
  await dialog.getByRole("button", { name: "影響の記録を一段ずつ辿る", exact: true }).click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await expect(results.locator("> [inert]")).toHaveCount(1);
  await page.unroute("**/neighbors?**");
  await dialog.getByRole("button", { name: "先頭から再取得", exact: true }).click();
  await expect(dialog.getByRole("alert")).toHaveCount(0);
  await expect(results).not.toHaveAttribute("data-updating", "true");
  await page.route("**/neighbors?**", async route => {
    if (new URL(route.request().url()).searchParams.get("predicates") === "CONTRIBUTED_TO") await new Promise(resolve => setTimeout(resolve, 650));
    await route.continue().catch(() => {});
  });
  const delayed = page.waitForRequest(request => request.url().includes("/neighbors?") && request.url().includes("CONTRIBUTED_TO"));
  await dialog.getByRole("button", { name: "作品のつくり手・別作品へ", exact: true }).click();
  await delayed;
  await expect(results.locator("> [inert]")).toHaveCount(1);
  await dialog.getByRole("button", { name: "研究機関を介して人に出会う", exact: true }).click();
  await expect(results).not.toHaveAttribute("data-updating", "true");
  await expect(results.getByTestId("prototype-claim").first()).toBeVisible();
  await page.waitForTimeout(800);
  await expect(results.getByTestId("prototype-claim").first()).toContainText("関わりがあった");
  await page.screenshot({ path: info.outputPath("institution.png") });
});
