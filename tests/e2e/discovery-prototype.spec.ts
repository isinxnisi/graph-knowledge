test("タップ反応・段階とタブのスクロール復元・版変更時の旧結果抑止", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(info.project.use.baseURL! + "/discovery-lab");
  const dialog = page.getByRole("dialog"), body = page.getByTestId("prototype-body"), results = page.getByTestId("prototype-results");
  await dialog.locator(`[data-seed="${pluto}"]`).getByRole("button").click();
  await expect(results).not.toHaveAttribute("data-updating", "true");
  const latency = await dialog.getByRole("button", { name: "二タブ", exact: true }).evaluate(async button => {
    const before = performance.now(); (button as HTMLButtonElement).click();
    await new Promise(requestAnimationFrame);
    return { ms: performance.now() - before, selected: button.getAttribute("aria-pressed") };
  });
  expect(latency.selected).toBe("true");
  console.log("prototype tap-to-next-frame", JSON.stringify(latency));
  await body.evaluate(el => { el.scrollTop = 100; });
  const before = await body.evaluate(el => el.scrollTop);
  await dialog.getByRole("tab", { name: "知識世界から", exact: true }).evaluate(el => (el as HTMLButtonElement).click());
  await expect(dialog.locator("[data-world]")).toHaveCount(11);
  await dialog.getByRole("tab", { name: "今ある接点から", exact: true }).evaluate(el => (el as HTMLButtonElement).click());
  await expect.poll(() => body.evaluate(el => el.scrollTop)).toBeCloseTo(before, 0);
  await page.route("**/neighbors?**", route => route.fulfill({ status: 409, contentType: "application/json", body: JSON.stringify({ error: { message: "Test revision changed" } }) }));
  await dialog.getByRole("button", { name: "影響の記録を一段ずつ辿る", exact: true }).click();
  await expect(dialog.getByRole("alert")).toContainText("公開KGの版が変わりました");
  await expect(results.locator("> [inert]")).toHaveCount(1);
  await page.unroute("**/neighbors?**");
  await dialog.getByRole("button", { name: "先頭から再取得", exact: true }).click();
  await expect(results).not.toHaveAttribute("data-updating", "true");
  await expect(dialog.getByRole("alert")).toHaveCount(0);
});
