import { test, expect } from "@playwright/test";
import { decodeExploration } from "../../lib/client/exploration-url";
import { workspaceLabels } from "../../lib/i18n/workspace";
import { relationText } from "../../lib/i18n/relation-condition";

test("same published film data: search, evidence, Graph and local save/restore", async ({ page }, info) => {
 await page.addInitScript(() => localStorage.setItem("plunode:privacy:v1", '{"analytics":false,"ads":false}'));
 await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
 expect((await (await page.request.get("/api/dataset")).json()).revision).toBe(process.env.PUBLICATION_TEST_REVISION);
 const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
 await page.goto("/");
 await page.getByTestId("discovery-search-entry").click();
 await page.getByTestId("preset-browser").locator('[data-catalog-result="other-works"]').getByRole("button", { name: "条件に合う対象を探す", exact: true }).click();
 const flow = page.getByTestId("discovery-connections");
 await flow.getByLabel("段ごとにRoleを指定（作品を起点）").check();
 await flow.getByRole("group", { name: "起点作品側", exact: true }).getByRole("button", { name: "監督", exact: true }).click();
 await flow.getByRole("group", { name: "別作品側", exact: true }).getByRole("button", { name: "脚本", exact: true }).click();
 await flow.getByRole("textbox").fill("インセプション");
 await flow.locator('[data-target-id="420865b6-1377-4d02-8678-09cf0ed28fac"]').getByRole("button", { name: "この対象から探す", exact: true }).click();
 await flow.getByRole("button", { name: "成立証拠と根拠を確認 ＋", exact: true }).click();
 await expect(flow).toContainText("インターステラー");
 await expect(flow.getByTestId("prototype-claim")).toHaveCount(2);
 await flow.getByRole("button", { name: "根拠を開く ＋", exact: true }).first().click();
 await flow.getByRole("button", { name: "根拠を開く ＋", exact: true }).first().click();
 await expect(flow).toContainText("クレジット / スタッフ / 監督 / クリストファー・ノーラン");
 await expect(flow).toContainText("クレジット / スタッフ / 脚本 / クリストファー・ノーラン");
 await page.screenshot({ path: info.outputPath("evidence.png"), fullPage: true });
 await flow.getByTestId("discovery-relation-graph").click();
 const rootId = "420865b6-1377-4d02-8678-09cf0ed28fac", person = "1b217c91-1e2d-46e1-9e4c-b90d706d3f7a";
 const model = () => decodeExploration(new URL(page.url()).searchParams.get("s")!, rootId, "public-kg");
 await expect(page.getByTestId("exploration-root")).toContainText("インセプション");
 const canvas = page.getByTestId("graph-canvas");
 const snapshot = () => canvas.evaluate(el => {
  const cy = (el as unknown as { _cyreg: { cy: import("cytoscape").Core } })._cyreg.cy;
  return { nodes: cy.nodes().map(n => n.id()).sort(), edges: cy.edges().map(e => e.id()).sort() };
 });
 await expect.poll(async () => (await snapshot()).nodes).toEqual([rootId, person].sort());
 const point = await canvas.evaluate((el, id) => {
  const cy = (el as unknown as { _cyreg: { cy: import("cytoscape").Core } })._cyreg.cy;
  const p = cy.getElementById(id).renderedPosition(), rect = el.getBoundingClientRect(); return { x: rect.x + p.x, y: rect.y + p.y };
 }, person);
 await page.mouse.click(point.x, point.y);
 await expect.poll(async () => (await snapshot()).nodes.length).toBe(3);
 await expect.poll(() => { const e = model().execution; return e.type === "pattern" && e.entityState?.branches.find(b => b.id === person)?.open; }).toBe(true);
 const expected = model().execution, graph = await snapshot(), ws = workspaceLabels("ja");
 const saved = page.locator("#explorer-search").getByRole("button", { name: ws.launch, exact: true });
 await saved.click(); let dialog = page.getByRole("dialog");
 await dialog.getByLabel(ws.name, { exact: true }).fill("互換検証：監督と脚本");
 await dialog.getByRole("button", { name: ws.save, exact: true }).click();
 await expect(dialog).toContainText(ws.saved); await dialog.getByRole("button", { name: ws.close, exact: true }).click();
 await page.locator("#explorer-graph").getByRole("button", { name: relationText("ja").free, exact: true }).click();
 await expect.poll(() => model().relation.type).toBe("adjacent");
 await saved.click(); dialog = page.getByRole("dialog"); await dialog.getByRole("button", { name: ws.open, exact: true }).click();
 await expect.poll(() => model().execution).toEqual(expected);
 await page.reload(); await expect.poll(snapshot).toEqual(graph);
 await page.getByRole("button", { name: "全体を表示", exact: true }).click();
 await page.screenshot({ path: info.outputPath("restored.png"), fullPage: true });
 expect(errors).toEqual([]);
});
