import { test, expect } from "@playwright/test";
import { decodeExploration } from "../../lib/client/exploration-url";
import { workspaceLabels } from "../../lib/i18n/workspace";
import { readingHref } from "../../lib/client/reading-reference";

// Fixed 34-Claim publication verification. Existing beta retains its earlier snapshot.
test("published AB: Nolan directing to screenwriting, evidence, Graph and restore", async ({ page }, info) => {
 test.skip(process.env.FILM_AB_PUBLICATION !== "1", "Only the explicitly selected published AB dataset");
 expect(info.project.use.baseURL).toBe("https://plunode.net");
 expect(process.env.FILM_FORMAL_REVISION).toBe("f5dbf83f-c89e-4e40-95ee-57957016089f");
 await page.addInitScript(() => localStorage.setItem("plunode:privacy:v1", '{"analytics":false,"ads":false}'));
 await page.setViewportSize({ width: 1440, height: 1000 });
 const errors: string[] = [];
 page.on("pageerror", error => errors.push(error.message));
 await page.route("**/*", route => new URL(route.request().url()).hostname === "plunode.net" ? route.continue() : route.abort());
 await page.goto("/");
 await page.getByTestId("discovery-search-entry").click();
 await page.getByTestId("preset-browser").locator('[data-catalog-result="other-works"]').getByRole("button", { name: "条件に合う対象を探す", exact: true }).click();
 const flow = page.getByTestId("discovery-connections");
 await flow.getByLabel("段ごとにRoleを指定（作品を起点）").check();
 const first = flow.getByRole("group", { name: "起点作品側", exact: true });
 const second = flow.getByRole("group", { name: "別作品側", exact: true });
 await first.getByRole("button", { name: "監督", exact: true }).click();
 await second.getByRole("button", { name: "脚本", exact: true }).click();
 await flow.getByRole("textbox").fill("インセプション");
 const row = flow.locator('[data-target-id="420865b6-1377-4d02-8678-09cf0ed28fac"]');
 await expect(row).toBeVisible();
 await row.getByRole("button", { name: "この対象から探す", exact: true }).click();
 await flow.getByRole("button", { name: "成立証拠と根拠を確認 ＋", exact: true }).click();
 await expect(flow).toContainText("インターステラー");
 await expect(flow).toContainText("クリストファー・ノーラン");
 await expect(flow.getByTestId("prototype-claim")).toHaveCount(2);
 await flow.getByRole("button", { name: "根拠を開く ＋", exact: true }).first().click();
 await flow.getByRole("button", { name: "根拠を開く ＋", exact: true }).first().click();
 await expect(flow).toContainText("クレジット / スタッフ / 監督 / クリストファー・ノーラン");
 await expect(flow).toContainText("クレジット / スタッフ / 脚本 / クリストファー・ノーラン");
 await expect(flow.getByRole("link", { name: "この記録の詳細ページへ" })).toHaveCount(2);
 await page.screenshot({ path: info.outputPath("nolan-proof.png"), fullPage: true });
 await flow.getByTestId("discovery-relation-graph").click();
 await expect(page.getByTestId("exploration-root")).toContainText("インセプション");
 const rootId = "420865b6-1377-4d02-8678-09cf0ed28fac", personId = "1b217c91-1e2d-46e1-9e4c-b90d706d3f7a";
 const model = () => decodeExploration(new URL(page.url()).searchParams.get("s")!, rootId, "public-kg");
 expect(model().relation).toMatchObject({ stepRoles: [["DIRECTING"], ["SCRIPT_WRITING"]] });
 const canvas = page.getByTestId("graph-canvas");
 const snapshot = () => canvas.evaluate(el => {
  const cy = (el as unknown as { _cyreg: { cy: import("cytoscape").Core } })._cyreg.cy;
  return { nodes: cy.nodes().map(n => ({ id: n.id(), label: n.data("label") })), edges: cy.edges().map(e => e.id()).sort() };
 });
 await expect.poll(async () => (await snapshot()).nodes.map(n => n.id).sort()).toEqual([rootId, personId].sort());
 const point = await canvas.evaluate((el, id) => {
  const cy = (el as unknown as { _cyreg: { cy: import("cytoscape").Core } })._cyreg.cy;
  const p = cy.getElementById(id).renderedPosition(), rect = el.getBoundingClientRect();
  return { x: rect.x + p.x, y: rect.y + p.y };
 }, personId);
 await page.mouse.click(point.x, point.y);
 await expect.poll(async () => (await snapshot()).nodes.length).toBe(3);
 await expect.poll(async () => (await snapshot()).edges.length).toBe(2);
 await expect.poll(() => {
  const execution = model().execution;
  return execution.type === "pattern" && execution.entityState?.branches.find(branch => branch.id === personId)?.open;
 }).toBe(true);
 const expected = model().execution, graph = await snapshot(), labels = workspaceLabels("ja");
 await page.locator("#explorer-search").getByRole("button", { name: labels.launch, exact: true }).click();
 let dialog = page.getByRole("dialog");
 await dialog.getByLabel(labels.name, { exact: true }).fill("公開済み映画34件の探索確認");
 await dialog.getByRole("button", { name: labels.save, exact: true }).click();
 await expect(dialog).toContainText(labels.saved);
 await dialog.getByRole("button", { name: labels.close, exact: true }).click();
 await page.reload();
 await page.locator("#explorer-search").getByRole("button", { name: labels.launch, exact: true }).click();
 dialog = page.getByRole("dialog");
 await dialog.getByRole("button", { name: labels.open, exact: true }).click();
 await expect.poll(() => model().execution).toEqual(expected);
 await expect.poll(snapshot).toEqual(graph);
 await page.getByRole("button", { name: "全体を表示", exact: true }).click();
 await page.screenshot({ path: info.outputPath("nolan-restored.png"), fullPage: true });
 await info.attach("published-ab-route", { body: JSON.stringify({ relation: model().relation, execution: expected, graph }), contentType: "application/json" });
 await page.goto(readingHref({ dataset: "public-kg", kind: "claim", id: "c100d4b3-373c-47ed-9007-04cd799ac0d2" }));
 await expect(page.getByText(/製作\s*資料表記の言語：ja/)).toBeVisible();
 await expect(page.getByText("参照箇所：クレジット / スタッフ / 製作 / クリストファー・ノーラン", { exact: true })).toBeVisible();
 await expect(page.getByTestId("film-trial-claim")).toHaveCount(0);
 expect(errors).toEqual([]);
});
