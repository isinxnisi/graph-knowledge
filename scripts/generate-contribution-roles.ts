// Static generation only. Catalog/reviews remain the authority for adoption.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { vocabularyHash } from "../lib/domain/vocabulary";
const directory = "vocabulary/contribution-roles/";
const read = (name: string) => readFileSync(directory + name, "utf8");
const catalogText = read("catalog.json"), reviewsText = read("reviews.json");
type Entry = { id: string; translations: Record<string, { label: string }> };
const catalog = JSON.parse(catalogText) as { entries: Entry[] };
const settingsText = read("codegen.json");
const settings = JSON.parse(settingsText) as {
 historicalAdoptedIds: string[]; historicalFilmDraftIds: string[]; fallbackLabels: Record<string, Record<string, string>>;
};
const ids = catalog.entries.map(entry => entry.id);
if (!ids.length || new Set(ids).size !== ids.length || ids.some(id => !/^[A-Z][A-Z0-9_]*$/.test(id))) throw Error("Invalid source Role IDs");
const labels = Object.fromEntries(["ja", "en"].map(locale => [locale, Object.fromEntries(catalog.entries.map(entry => {
 const label = entry.translations[locale]?.label ?? settings.fallbackLabels[locale]?.[entry.id];
 if (!label) throw Error(`Missing existing ${locale} label: ${entry.id}`);
 return [entry.id, label];
}))]));
for (const list of [settings.historicalAdoptedIds, settings.historicalFilmDraftIds]) if (list.some(id => !ids.includes(id))) throw Error("Historical cohort removed");
const hash = (text: string) => createHash("sha256").update(text).digest("hex");
const value = {
 schemaVersion: 1, fixtureSchemaVersions: [4], serialization: ["fixture-v4-schema-json-2lf-v1"],
 scopeFormats: ["null", "publication-isbn13-v1"], savedWorkspaceVersions: [1, 2, 3], relationRevisions: [1, 2, 3],
 recognizedRoleIds: ids, definitionHashes: Object.fromEntries(catalog.entries.map(entry => [entry.id, vocabularyHash(entry)])),
 catalogSha256: hash(catalogText), reviewsSha256: hash(reviewsText),
 codegenSha256: hash(settingsText), labelsSha256: vocabularyHash(labels),
};
const outputs: Record<string, string> = {
 "lib/generated/contribution-roles.ts": "// Generated by scripts/generate-contribution-roles.ts. Do not edit.\n" +
  `export const CONTRIBUTION_ROLE_IDS = ${JSON.stringify(ids)} as const;\n` +
  `export const HISTORICAL_ADOPTED_ROLE_IDS = ${JSON.stringify(settings.historicalAdoptedIds)} as const;\n` +
  `export const HISTORICAL_FILM_DRAFT_ROLE_IDS = ${JSON.stringify(settings.historicalFilmDraftIds)} as const;\n` +
  `export const CONTRIBUTION_ROLE_LABELS = ${JSON.stringify(labels, null, 2)} as const;\n` +
  `export const CONTRIBUTION_ROLE_COMPATIBILITY = ${JSON.stringify(value, null, 2)} as const;\n`,
 "vocabulary/contribution-roles/generated-compatibility.json": JSON.stringify(value, null, 2) + "\n",
};
const check = process.argv.slice(2);
if (check.length > 1 || check.length === 1 && check[0] !== "--check") throw Error("Only --check is supported");
for (const [path, content] of Object.entries(outputs)) {
 if (check.length) { if (readFileSync(path, "utf8") !== content) throw Error(`Generated Role output differs: ${path}`); }
 else { mkdirSync(path.substring(0, path.lastIndexOf("/")), { recursive: true }); writeFileSync(path, content); }
}
console.log(JSON.stringify({ generated: !check.length, checked: !!check.length, roles: ids.length }));
